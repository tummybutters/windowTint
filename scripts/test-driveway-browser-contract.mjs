import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {normalizeQuote}=require('../lib/automotive-quote');
const {contextFor}=require('../assets/quote/package-context');
const source=fs.readFileSync('assets/quote/package-quote.js','utf8');
const helpers=source.slice(0,source.indexOf('const $='));
const submit=source.match(/^async function submitStep\(\).*$/m)[0];
const filename='assets/quote/driveway-tracking.js';
const tracking=fs.existsSync(filename)?fs.readFileSync(filename,'utf8'):'';
const url='https://www.obsidianautoworksoc.com/driveway-package?gclid=click-test&utm_campaign=123&utm_medium=cpc&name=PRIVATE';
const link={href:'https://www.obsidianautoworksoc.com/package/'};
const host={location:new URL(url),obsidianLeadTracking:{getLead:()=>({session_id:'session-test'})},gtag(){}};
vm.runInNewContext(tracking,{window:host,location:host.location,URL,URLSearchParams,document:{querySelectorAll:()=>[link]}});
assert.equal(host.ObsidianOffer?.offer_id,'driveway_package');
assert.equal(host.ObsidianExperiment,undefined,'Full rollout cannot be labeled as the retired A/B test');
assert.equal(new URL(link.href).searchParams.get('gclid'),'click-test','Offer CTA must retain the ad click through to the package quiz');
assert.equal(new URL(link.href).searchParams.get('utm_campaign'),'123');
assert(!new URL(link.href).searchParams.has('name'),'Only marketing attribution is forwarded');
for(const upgrade of ['FREE sunroof tint','FREE sun strip']){
 const ctx=contextFor('/package/');
 assert.equal(ctx.answers.coverage,'Sides + rear');
 assert.equal(ctx.answers.package,'Driveway Package');
 const calls=[],requests=[],button={disabled:false},error={textContent:''};
 const win={...host,location:new URL(link.href),gtag:(...args)=>calls.push(args)};win.parent=win;
 const answers={...ctx.answers,upgrade,type:'Car',vehicle:'2024 Example sedan',address:'123 Example Lane, Irvine CA 92618',name:'PRIVATE',phone:'7145550123'};
 const box={window:win,location:win.location,URLSearchParams,Set,document:{querySelector:()=>({value:''})},state:{id:'9c2f8d24-d2d1-49fb-aefe-9a9ec2702b47',answers,busy:false},fields:[],captureFields(){},$:s=>s==='#error'?error:button,screen:{querySelector:()=>({setAttribute(){},focus(){}})},render(){},fetch:async(url,opt)=>{requests.push({url,body:JSON.parse(opt.body)});return{ok:true,json:async()=>({ok:true,id:box.state.id})}}};
 vm.createContext(box);vm.runInContext(helpers+'\n'+submit,box);await vm.runInContext('submitStep()',box);
 assert.equal(requests[0].url,'/api/automotive-quotes','Production package uses the real durable intake endpoint');
 const record=normalizeQuote(requests[0].body);
 assert.equal(record.details.upgrade,upgrade);
 assert.equal(record.attribution.experiment_variant,undefined);
 assert.equal(record.attribution.gclid,'click-test');
 assert.equal(record.attribution.utm_campaign,'123');
 assert(!JSON.stringify(calls).includes('PRIVATE'));
 assert.equal(calls.filter(c=>c[1]==='conversion').length,1);
 await vm.runInContext('submitStep()',box);
 assert.equal(calls.filter(c=>c[1]==='conversion').length,1,'Duplicate successful response cannot double count');
}
console.log('Production package frontend carries both upgrades, offer labels and click attribution to durable intake; tracking excludes customer data and deduplicates conversions.');
